#!/bin/sh
# Build a single-file version of the simulator for distribution
# (e-mail, ILIAS/Moodle upload, student download):
# inlines styles.css, model.js and app.js into index.html -> dist/wave_simulator.html
set -e
cd "$(dirname "$0")"
mkdir -p dist
python3 - <<'EOF'
html = open('index.html', encoding='utf-8').read()
def inline(html, tag, open_tag, close_tag, path):
    if html.count(tag) != 1:
        raise SystemExit(f'build.sh: expected exactly one {tag} in index.html')
    return html.replace(tag, open_tag + '\n' + open(path, encoding='utf-8').read() + close_tag)

html = inline(html, '<link rel="stylesheet" href="styles.css">', '<style>', '</style>', 'styles.css')
for js in ('model.js', 'app.js'):
    html = inline(html, f'<script src="{js}"></script>', '<script>', '</script>', js)
html = html.replace('<html lang="en">',
    '<html lang="en">\n<!-- Generated by build.sh from index.html, styles.css, model.js and app.js. Do not edit. -->', 1)
open('dist/wave_simulator.html', 'w', encoding='utf-8').write(html)
EOF
echo "Built dist/wave_simulator.html"
